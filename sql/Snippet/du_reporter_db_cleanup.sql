-- change the company and date where conditions on each for what needs to be cleaned up, this could probably be better written with a batch while loop.

DELETE FROM UNI_EVT_RELAUNCHES  
WHERE (CONVERT(VARCHAR(32),RELAUNCH_ID)) IN ( 
        SELECT  TOP 100000 CONVERT(VARCHAR(32),l.RELAUNCH_ID)
        FROM UNI_EVT_RELAUNCHES l,
             UNI_EVT_DATASOURCES d
        WHERE l.DATASOURCE_ID=d.DATASOURCE_ID
        AND d.COMPANY_NAME = 'DHSTST'
        AND l.STARTING_EVT_TIME < CONVERT(DATETIME, '2024-09-11 08:34:26', 120) )

DELETE FROM UNI_EVT_INTERVENTIONS 
WHERE (CONVERT(VARCHAR(32),HISTORY_OEXID_NUMLAUNCH)) IN ( 
        SELECT TOP 100000 CONVERT(VARCHAR(32),l.RELAUNCH_ID)
        FROM UNI_EVT_RELAUNCHES l,
             UNI_EVT_DATASOURCES d
        WHERE l.DATASOURCE_ID=d.DATASOURCE_ID 
        AND d.COMPANY_NAME = 'DHSTST'
        AND l.STARTING_EVT_TIME < CONVERT(DATETIME, '2024-09-11 08:34:26', 120) )


DELETE FROM UNI_EVT_LOG
WHERE LOG_ID IN  (
    SELECT l.LOG_ID
    FROM UNI_EVT_LOG l 
        LEFT JOIN UNI_EVT_EXTRACTIONS e ON l.LOG_ID = e.LOG_ID
        LEFT JOIN UNI_EVT_PURGES p ON l.LOG_ID = p.LOG_ID
        LEFT JOIN UNI_EVT_REPORTS r ON l.LOG_ID = r.LOG_ID
    WHERE p.LOG_ID IS NULL AND e.LOG_ID IS NULL AND r.LOG_ID IS NULL  )