DECLARE @PREVIOUSDATE DATETIME =DATEADD(hour, 6, DATEADD(day, -1, DATEDIFF(DAY, 0, CURRENT_TIMESTAMP)));
DECLARE  @TODAYSDATE DATETIME =DATEADD(day, 1, @PREVIOUSDATE);
SELECT 'Report Running For @PREVIOUSDATE: ' ,Cast(@PREVIOUSDATE  AS VARCHAR(30));
SELECT 'Report Running For @TODAYSDATE: ' ,Cast(@TODAYSDATE  AS VARCHAR(30));

 
--Query 1 - Total number of new MCIs created by system/agency
--TOTAL NUMBER OF NEW MCIS CREATED BY SYSTEM/AGENCY
SELECT  COUNT(PartyId) AS 'MCIs CREATED',CreatedBy AS 'CREATED BY SYSTEMID'from NodeParty WITH(NOLOCK)
WHERE CreatedDateTime  BETWEEN @PREVIOUSDATE AND @TODAYSDATE 
and PartyTypeId = 1
GROUP BY CreatedBy


--Query 2 - Total number of MCI updates  by system agency 
--TOTAL NUMBER OF MCI UPDATES BY SYSTEM AGENCY
SELECT COUNT(DISTINCT PartyId) AS 'MCIs UPDATED',CreatedBy AS 'UPDATED BY SYSTEMID' from PartyHistory PH WITH(NOLOCK)
WHERE PH.CreatedDateTime  between  @PREVIOUSDATE AND @TODAYSDATE 
GROUP BY PH.CreatedBy