USE [db_$UReporter_PROD]

SELECT TOP (5)
    TASK_NAME,
    MANAGEMENT_UNIT_NAME,
    RUNNING_EVT_TIME,
    ENDING_EVT_TIME,
    case FINAL_STATUS WHEN 'T' THEN 'COMPLETED' WHEN 'I' THEN 'ABORTED' end

FROM UNI_EVT_RELAUNCHES
WHERE MANAGEMENT_UNIT_NAME = 'APP_AWW_PROD_01'
    and TASK_NAME = 'AWW_1095B_CREATE_IRS_XML_WEEKLY'
    and ENDING_EVT_TIME IS NOT NULL
order by ENDING_EVT_TIME desc